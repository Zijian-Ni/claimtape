export function t(lang, key) {
  const keys = key.split('.');
  let obj = i18n[lang] || i18n.en;
  for (const k of keys) {
    obj = obj?.[k];
    if (obj === undefined) {
      // fallback to en
      obj = i18n.en;
      for (const k2 of keys) obj = obj?.[k2];
      break;
    }
  }
  return obj ?? key;
}
